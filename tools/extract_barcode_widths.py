#!/usr/bin/env python3
"""Extract Code 39 element widths from rendered barcode sample pages.

Usage:
    pdftoppm -r 150 -gray "Barcode Sample.pdf" page
    python3 extract_barcode_widths.py page-*.pgm > testing/host/barcode_samples.h

Each page is scanned along one horizontal row through the bars (above the
printed label). Runs of dark/light pixels become element widths, quiet
zones are dropped, and the result is written as a C header that the host
unit test feeds to barcode_decode(). This is the A7 evidence path: the
decoder is tested on the real sample sheet, not only synthetic data.

Owner: Buddy 3 (LIM JUN HAO).
"""

import sys
from PIL import Image

DARK = 128


def widths_from_row(row):
    """Run-length encode one pixel row; drop the outer quiet zones."""
    runs = []
    colour = row[0] < DARK
    length = 0
    for pixel in row:
        is_dark = pixel < DARK
        if is_dark == colour:
            length += 1
        else:
            runs.append((colour, length))
            colour = is_dark
            length = 1
    runs.append((colour, length))
    # Strip leading/trailing light runs (quiet zones and page margins).
    while runs and not runs[0][0]:
        runs.pop(0)
    while runs and not runs[-1][0]:
        runs.pop()
    return [length for _, length in runs]


def main(paths):
    print("/* Generated by tools/extract_barcode_widths.py - do not edit. */")
    print("/* Element widths in pixels at 150 dpi from Barcode Sample.pdf. */")
    print("#ifndef BARCODE_SAMPLES_H")
    print("#define BARCODE_SAMPLES_H")
    print("#include <stdint.h>")
    for index, path in enumerate(paths):
        image = Image.open(path).convert("L")
        width, height = image.size
        row = [image.getpixel((x, height // 4)) for x in range(width)]
        widths = widths_from_row(row)
        values = ", ".join(str(w) for w in widths)
        print(f"static uint16_t const g_sample_{index}[] = {{ {values} }};")
        print(f"#define SAMPLE_{index}_COUNT ({len(widths)}u)")
    print("#endif")


if __name__ == "__main__":
    main(sys.argv[1:])
